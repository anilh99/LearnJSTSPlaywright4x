let x=10;
let y=20;
console.log(x==y);
console.log(5=="5");
console.log(5==="5");
// == is a comparison operator that checks if the values of two operands are equal or not. If the values are equal, it returns true; otherwise, it returns false. In this case, since x is 10 and y is 20, the comparison x==y will return false.
// === is a strict equality operator that checks if the values and types of two operands are equal or not. If both the values and types are equal, it returns true; otherwise, it returns false. In this case, since x is 10 (a number) and y is 20 (also a number), the comparison x===y will return false.
// !== is a strict inequality operator that checks if the values and types of two operands are not equal. If both the values and types are not equal, it returns true; otherwise, it returns false.

console.log(5!==5);

